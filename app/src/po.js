// Purchase order as a printable page: the browser's "Save as PDF" makes the file.
import { ESCROW } from './chain.js';
import { ccdToMicro, microToCcd } from './codec.js';
import { CAST } from './cast.js';
import { h } from './ui.js';

export function printPO(d) {
  document.getElementById('po')?.remove();
  const today = new Date().toLocaleDateString(undefined, { day: 'numeric', month: 'long', year: 'numeric' });
  const po = h('article#po', { 'aria-hidden': 'true' },
    h('header.po-h',
      h('div', h('div.po-brand', h('span.flag'), 'Clear to Pay'), h('p', 'Purchase order')),
      h('dl', h('dt', 'Order'), h('dd', d.orderId ? `#${d.orderId}` : 'Draft'), h('dt', 'Date'), h('dd', today))),
    h('section.po-parties',
      h('div', h('h4', 'Buyer'), h('p', h('span.mono', CAST.buyer))),
      h('div', h('h4', 'Supplier'), h('p', d.supplierName, h('br'), h('span.mono', d.supplier)))),
    h('table.po-lines',
      h('thead', h('tr', h('th', 'Item'), h('th', 'Quantity'), h('th', 'Unit price'), h('th', 'Amount'))),
      h('tbody', d.lines.map((l) => h('tr', h('td', l.item), h('td', l.qty), h('td', `${l.price} CCD`), h('td', `${microToCcd(BigInt(l.qty) * ccdToMicro(l.price))} CCD`)))),
      h('tfoot', h('tr', h('td', 'Total'), h('td', String(d.units)), h('td'), h('td', `${microToCcd(d.micro)} CCD`)))),
    d.place ? h('p', h('b', 'Deliver to: '), d.place) : null,
    d.notes ? h('p', h('b', 'Notes: '), d.notes) : null,
    h('section.po-terms',
      h('h4', 'How this order is paid'),
      h('ol',
        h('li', `The amount is held in the escrow contract <${ESCROW.index},${ESCROW.subindex}> on Concordium testnet.`),
        h('li', `At delivery, the buyer’s receiver (${d.receiver}) and your delivery rep each count without seeing the other’s number; payment needs both to match the order.${d.approver?.trim() ? ` The buyer’s approver (${d.approver.trim()}) may also check inside.` : ''}`),
        d.referee?.trim() ? h('li', `Disputes over a counted delivery are settled by the referee: ${d.referee.trim()}.`) : null,
        h('li', 'The supplier approves the invoice and its amount from its own account.'),
        h('li', 'The contract pays only the payout account the supplier registered itself, and only after that account has waited out its hold (72 hours in production).'))),
    h('footer.po-f', 'Generated by Clear to Pay. The escrow contract, not this document, decides payment.'));
  document.body.append(po);
  window.print();
}
